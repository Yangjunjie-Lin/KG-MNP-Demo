def test_final_zip_is_reopened_and_external_hash_is_independent(stage_archive_files, tmp_path):
    from zhigou_toolchain.modeling.delivery.stage import (
        export_stage,
        verify_stage_archive,
    )
    path = tmp_path / "stage.zip"
    result = export_stage(path, stage_archive_files)
