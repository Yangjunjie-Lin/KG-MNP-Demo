def test_context_tampering_rehashed_outer_manifest_still_rejected(stage_archive_files):
    from zhigou_toolchain.modeling.delivery.exchange_io import file_rows
    from zhigou_toolchain.modeling.delivery.stage import verify_stage_files
    altered = dict(stage_archive_files)
    name = "hr/diagnostics/local-trace.json"
    trace = json.loads(altered[name])
    trace["bindings"]["delivery_target"]["native_archive_sha256"] = "0" * 64
    altered[name] = json_bytes(trace)
    manifest = json.loads(altered["stage_manifest.json"])
    sizes = {r["path"]: r for r in file_rows({n: v for n, v in altered.items() if n != "stage_manifest.json"})}
    for row in manifest["files"]:
        row.update(sizes[row["path"]])
    altered["stage_manifest.json"] = json_bytes(manifest)
    with pytest.raises(ValueError, match="DELIVERY_TARGET_MISMATCH"):
        verify_stage_files(altered)


def native_files(raw):
    import zipfile
    from io import BytesIO
    with zipfile.ZipFile(BytesIO(raw)) as archive:
        return {n: archive.read(n) for n in archive.namelist()}


def recompose(files, bindings):
    deps = {n.removeprefix("dependencies/"): raw for n, raw in files.items() if n.startswith("dependencies/") and n != "dependencies/run_bindings.json"}
    return handoff_files(files["native/ontology.kgop"], native_files(files["native/ontology.kgop"]), bindings, deps)


def test_actual_negative_results_are_bound_and_categorized(stage_case):
    files = stage_case["files"]
    verified = verify_handoff(files, trusted_receipt=stage_case["receipt"])
    assert verified["format"] == "zhigou-ontology-handoff/1.1.0"
    assert verified["stage_acceptance"] == "PASS"
    payload = json.loads(files["tests/negative_cases.json"])
    assert payload["status"] == "PASS" and len(payload["report"]["cases"]) == 14
    assert {c["category"] for c in payload["report"]["cases"]} == {"SHACL", "PROVENANCE", "FILE_INTEGRITY", "STATE_GATE", "AUTHORIZATION", "DELIVERY_BINDING"}
    for row in payload["report"]["cases"]:
        assert row["status"] == "PASS" and row["observed"]["status"] == "DETECTED"
        assert row["tested_native_archive_sha256"] == digest(files["native/ontology.kgop"])
        assert digest(files["dependencies/" + row["input_artifact"]]) == row["mutated_input_sha256"]
    assert json.loads(files["mapping.json"])["native_execution_policy"] == "DECLARATIVE_NOT_EXECUTED"
    from zhigou_toolchain.modeling.control_plane.service import ModelingWorkspaceService
    workspace = ModelingWorkspaceService(get_project(stage_case["service"].root, stage_case["project_id"]).root)
    requests = (workspace.proposal_directory(stage_case["proposed"]["proposal"]["proposal_id"]) / "provider-requests.json").read_text(encoding="utf-8")
    assert "negative_case_plan" not in requests and payload["plan"]["plan_id"] not in requests


def test_immutable_ancestry_accepts_earlier_revision_and_rejects_tampering(stage_case):
    files, diagnostic = stage_case["files"], stage_case["diagnostic"]
    cover = compose(downstream=files, diagnostic=diagnostic)
    assert verify_cover(cover)["status"] == "VERIFIED"
    assert json.loads(cover["handoff_manifest.json"])["outputs"]["evolution"]["status"] == "BLOCKED"
    trace = json.loads(diagnostic["local-trace.json"])
    relation = associate_trace(trace, files)
    assert relation["relationship"] == "CURRENT_NATIVE_DEPENDENCY_ANCESTOR"
    b = json.loads(files["dependencies/run_bindings.json"])
    early = next(o for o in b["agent_runs"] if o["operation_id"] == "modeling.scope")
    assert early["session_revision"] < b["session_revision"]
    verify_ancestor(early, b["session_snapshot"])
    for key in ("package_id", "native_archive_sha256", "input_run_id", "session_revision", "compilation_plan_id"):
        changed = deepcopy(trace)
        changed["bindings"]["delivery_target"][key] = "WRONG"
        with pytest.raises(ValueError, match="DELIVERY_TARGET_MISMATCH"):
            associate_trace(changed, files)
    changed = deepcopy(trace)
    changed["bindings"]["job_id"] = "unrelated-job-in-same-session"
    with pytest.raises(ValueError, match="RUN_REFERENCE"):
        associate_trace(changed, files)
    changed = deepcopy(trace)
    changed["harness_manifest"]["resources"]["rules"] = {"altered": True}
    with pytest.raises(ValueError, match="HARNESS_START"):
        validate_trace_context(changed)


def test_rehashed_manifest_does_not_authorize_swapped_plan_or_results(stage_case):
    files = stage_case["files"]
    b = json.loads(files["dependencies/run_bindings.json"])
    b["negative_case_results"]["target"]["native_archive_sha256"] = "0" * 64
    tampered = recompose(files, b)
    with pytest.raises(ValueError, match="TARGET_MISMATCH"):
        verify_handoff(tampered)
    b = json.loads(files["dependencies/run_bindings.json"])
    b["negative_case_plan"]["version"] = "changed-after-freeze"
    with pytest.raises(ValueError, match="FREEZE|ORIGIN|PLAN"):
        verify_handoff(recompose(files, b))
    # Even an internally self-consistent attacker cannot replace the out-of-band
    # authorized service export receipt by rehashing the package's own manifest.
    b = json.loads(files["dependencies/run_bindings.json"])
    b["recipient"] = "another-recipient"
    tampered = recompose(files, b)
    with pytest.raises(ValueError, match="TRUSTED_EXPORT"):
        verify_handoff(tampered, trusted_receipt=stage_case["receipt"])


def test_no_plan_and_missing_rule_never_become_pass(stage_case, tmp_path, monkeypatch):
    files = stage_case["files"]
    native = native_files(files["native/ontology.kgop"])
    plan = deepcopy(json.loads(files["tests/negative_cases.json"])["plan"])
    plan["cases"] = plan["cases"][:1]
    plan["cases"][0]["rule_basis"]["shape_iri"] = "urn:not-a-domain-rule"
    result, _ = execute_negative_plan(plan, files, native, output=tmp_path / "not-applicable")
    assert result["status"] == "INCOMPLETE" and result["cases"][0]["status"] == "NOT_APPLICABLE"
    plan["cases"][0]["rule_basis"]["shape_iri"] = json.loads(files["tests/negative_cases.json"])["plan"]["cases"][0]["rule_basis"]["shape_iri"]
    monkeypatch.setattr("zhigou_toolchain.modeling.delivery.negative.shacl_check", lambda _: {"status": "TIMEOUT"})
    result, _ = execute_negative_plan(plan, files, native, output=tmp_path / "timeout")
    assert result["status"] == "FAIL" and result["cases"][0]["status"] != "PASS"


def test_plan_cannot_weaken_expected_rejection_and_is_excluded_from_content_logs():
    plan = plan_for("hr")
    assert normalize_plan(plan)["cases"]
    plan["cases"][0]["expected"]["code"] = "always-accept"
    with pytest.raises(ValueError):
        normalize_plan(plan)
    changes = set()
    safe = public_value({"negative_case_plan": plan}, changes)
    assert safe["negative_case_plan"] == "[REDACTED]" and changes


def test_stage_one_ancestor_does_not_require_later_tool_configuration():
    from zhigou_toolchain.contracts.canonical import semantic_hash
    frozen = {"run_id": "r", "configuration": {"model": "old"}}
    output = {"job_id": "j", "status": "CURRENT", "operation": "modeling.scope", "stage": 1, "dependency_digest": semantic_hash(frozen)}
    observation = {"job_id": "j", "operation_id": "modeling.scope", "session_id": "s", "session_revision": 1,
                   "session_output": output, "frozen_dependency_sha256": semantic_hash(frozen), "dependency_parts": dependency_parts(frozen)}
    session = {"session_id": "s", "revision": 9, "outputs": [output], "frozen": {**frozen, "configuration": {"model": "new"}}}
    verify_ancestor(observation, session)
    session["outputs"][0]["status"] = "STALE"
    with pytest.raises(ValueError, match="ANCESTOR_NOT_CURRENT"):
        verify_ancestor(observation, session)
