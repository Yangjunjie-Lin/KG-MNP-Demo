"""User-authorized experiment activation and bounded POST readiness probe.

No research prediction is generated by activation. It records the latest
explicit user instruction and the previously disclosed absolute budget caps.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from zhigou_toolchain.modeling.five_stage.compatible import configured_client
from zhigou_toolchain.ontology_io.cli import load, save
from zhigou_toolchain.ontology_io.contracts import Protocol
from zhigou_toolchain.ontology_io.live_broker import dispatch
from zhigou_toolchain.ontology_io.live_budget import BudgetLedger


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, required=True)
    args = parser.parse_args()
    args.workspace.mkdir(parents=True, exist_ok=True)
    authorization = {"user_request": "你帮我直接启用全量实验吧，在过程中有问题则直接进行修复就行",
        "max_calls": 325311, "max_reserved_tokens": 10659790848,
        "scope": "PREVIOUSLY_DISCLOSED_FULL_CALL_PACK_PLUS_PREFLIGHT_WITHIN_SAME_GLOBAL_CAP",
        "data_licenses_and_safety_boundaries": "UNCHANGED", "no_automatic_budget_increase": True,
        "spend_limit_currency": None, "probes_and_failures_consume_budget": True}
    ledger = BudgetLedger(args.workspace / "budget.sqlite")
    ledger.initialize(authorization)
    auth_file = args.workspace / "authorization.json"
    if auth_file.exists() and load(auth_file) != authorization:
        raise ValueError("AUTHORIZATION_FILE_CHANGED")
    if not auth_file.exists():
        save(auth_file, authorization)
    probe_file = args.workspace / "probe-result.json"
    if probe_file.exists():
        print(json.dumps({"status": "ACTIVATED_PRIOR_PROBE_RETAINED", "probe": load(probe_file)["status"], "budget": ledger.snapshot()}))
        return
    client = configured_client()
    try:
        model, revision = client.lock.model_id, client.lock.revision
        effort = getattr(client, "reasoning_effort", None)
        health = client.health()
    finally:
        client.close()
    protocol = Protocol.model_validate({"protocol_id": "authorized-synthetic-post-readiness-v1", "model_id": model,
        "declared_revision": revision, "reasoning_effort": effort, "systems": ["DirectGeneralLLM"], "replicates": 1,
        "request_profile": {"completion_token_parameter": "max_completion_tokens", "timeout_seconds": 120},
        "budget": {"max_calls": 1, "max_output_tokens": 1024, "max_total_tokens": 32768}})
    request = {"instruction": "Return exactly the JSON object requested by the schema. This is a synthetic parameter probe, not a research sample.",
        "content": {"instruction": "Set ok to true."}, "schema": {"type": "object", "additionalProperties": False,
            "properties": {"ok": {"const": True}}, "required": ["ok"]}, "allowed_iris": []}
    reply = dispatch(request, protocol=protocol, ledger=ledger, job_id="preflight", request_id="preflight-post-1",
        directory=args.workspace / "probe-1")
    status = "POST_PROBE_SUCCEEDED" if reply["ok"] else "POST_PROBE_FAILED"
    save(probe_file, {"status": status, "health": health, "protocol": protocol.model_dump(mode="json"),
        "reply": reply, "budget": ledger.snapshot(), "benchmark_score": None,
        "qualification": "REQUEST_ACCEPTED_AND_SCHEMA_CHECKED_NOT_PROOF_ALL_PARAMETERS_ENFORCED"})
    print(json.dumps({"status": status, "budget": ledger.snapshot(), "benchmark_score": None}))


if __name__ == "__main__":
    main()
